public class casebased2 {
public static void main(String[] args) {
  char var = 'r';
  switch (var) {
    case 'r':
        System.out.println("you are going to become an adult");
   break;
   case 'c':
    System.out.println("you are going to join an job");
    break;
    case 'd':
    System.out.println("you are going to get retiered ");
    break;
    default:
    System.out.println("enjoy your life");
        break;
  }
  System.out.println("thanks for using my code");
}    
}
